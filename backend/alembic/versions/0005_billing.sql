CREATE TABLE plans (
 id text PRIMARY KEY, name text NOT NULL, active boolean NOT NULL DEFAULT true,
 created_at timestamptz NOT NULL DEFAULT now()
);
-- statement
CREATE TABLE plan_versions (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), plan_id text NOT NULL REFERENCES plans(id),
 version integer NOT NULL CHECK(version > 0), price_minor_units integer NOT NULL CHECK(price_minor_units >= 0),
 currency text NOT NULL CHECK(currency = 'TRY'), monthly_quota integer NOT NULL CHECK(monthly_quota > 0),
 background_tier text NOT NULL CHECK(background_tier IN ('basic','full')),
 trial_period_days integer NOT NULL DEFAULT 0 CHECK(trial_period_days BETWEEN 0 AND 7),
 iyzico_product_reference_code text, iyzico_pricing_plan_reference_code text UNIQUE,
 iyzico_trial_plan_reference_code text UNIQUE,
 published_at timestamptz, retired_at timestamptz, UNIQUE(plan_id,version),
 CHECK(price_minor_units = 0 OR published_at IS NULL OR (iyzico_product_reference_code IS NOT NULL AND iyzico_pricing_plan_reference_code IS NOT NULL)),
 CHECK(trial_period_days = 0 OR iyzico_trial_plan_reference_code IS NOT NULL),
 CHECK(price_minor_units > 0 OR trial_period_days = 0)
);
-- statement
CREATE UNIQUE INDEX plan_versions_live ON plan_versions(plan_id) WHERE published_at IS NOT NULL AND retired_at IS NULL;
-- statement
CREATE TABLE subscriptions (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), user_id uuid UNIQUE REFERENCES auth.users(id) ON DELETE SET NULL,
 provider text CHECK(provider = 'iyzico'), provider_subscription_reference text UNIQUE,
 status text NOT NULL DEFAULT 'active' CHECK(status IN ('active','trialing','past_due','canceling','canceled','suspended','expired')),
 access_until timestamptz, trial_used_at timestamptz, renewal_check_after timestamptz,
 deletion_requested_at timestamptz, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
-- statement
CREATE TABLE subscription_periods (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), subscription_id uuid NOT NULL REFERENCES subscriptions(id),
 user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL, plan_version_id uuid NOT NULL REFERENCES plan_versions(id),
 provider_subscription_reference text, provider_order_reference text UNIQUE,
 starts_at timestamptz NOT NULL, ends_at timestamptz NOT NULL CHECK(ends_at > starts_at),
 quota_snapshot integer NOT NULL CHECK(quota_snapshot > 0), used_this_period integer NOT NULL DEFAULT 0 CHECK(used_this_period >= 0 AND used_this_period <= quota_snapshot),
 status text NOT NULL DEFAULT 'active' CHECK(status IN ('pending','active','superseded','expired','suspended')),
 created_at timestamptz NOT NULL DEFAULT now(), closed_at timestamptz
);
-- statement
