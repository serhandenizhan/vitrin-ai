DECLARE accepted_version text;
BEGIN
 accepted_version := nullif(new.raw_user_meta_data ->> 'terms_version','');
 IF accepted_version IS NULL OR new.raw_user_meta_data ->> 'terms_accepted' IS DISTINCT FROM 'true' THEN RETURN new; END IF;
 INSERT INTO public.user_consents(user_id,document_type,document_version)
 VALUES(new.id,'terms',accepted_version),(new.id,'kvkk_notice',accepted_version)
 ON CONFLICT(user_id,document_type,document_version) WHERE checkout_session_id IS NULL DO NOTHING;
 RETURN new;
END $$;
