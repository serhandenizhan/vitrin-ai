CREATE FUNCTION public.billing_signup() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE sid uuid; pv public.plan_versions;
BEGIN
 SELECT * INTO STRICT pv FROM public.plan_versions WHERE plan_id='deneme' AND published_at IS NOT NULL AND retired_at IS NULL;
 INSERT INTO public.subscriptions(user_id,access_until) VALUES(new.id,now()+interval '1 month') RETURNING id INTO sid;
 INSERT INTO public.subscription_periods(subscription_id,user_id,plan_version_id,starts_at,ends_at,quota_snapshot)
 VALUES(sid,new.id,pv.id,now(),now()+interval '1 month',pv.monthly_quota);
 RETURN new;
END $$;
